//! The reader of `Cargo.lock`.

use super::{At, Dep, Parsed, Source};

/// crates.io's index, in both forms Cargo writes it.
const CRATES_IO: [&str; 2] = [
    "registry+https://github.com/rust-lang/crates.io-index",
    "sparse+https://index.crates.io/",
];

/// `Cargo.lock`: every table of the array `package`, its name, version and source, at the line
/// of its name. The file is TOML and is parsed whole by the `toml` crate, so a comment, a literal
/// string or keys in any order read as cargo reads them. A crate with no source is a path or
/// workspace crate, including one patched to a path. `[[patch.unused]]` entries are patches the
/// build does not use, not dependencies. A file that is not TOML, a `package` that is not an
/// array of tables, and an entry whose name or version is missing or not a string, or whose
/// source is not a string, fail the reading: an entry is never skipped.
pub(super) fn cargo(text: &str) -> Parsed {
    use toml::de::{DeTable, DeValue};
    let Ok(lock) = DeTable::parse(text) else {
        return Parsed::Failed;
    };
    let packages = match lock.get_ref().get("package").map(|p| p.get_ref()) {
        None => &[][..],
        Some(DeValue::Array(packages)) => &packages[..],
        Some(_) => return Parsed::Failed,
    };
    // Where each line break is, to tell the line of a name from its offset.
    let breaks: Vec<usize> = text.match_indices('\n').map(|(i, _)| i).collect();
    let mut out = Vec::new();
    for package in packages {
        let DeValue::Table(package) = package.get_ref() else {
            return Parsed::Failed;
        };
        // A key's offset and its value as a string; `None` inside for a value of another type.
        let string = |key: &str| {
            package
                .get_key_value(key)
                .map(|(k, v)| (k.span().start, v.get_ref().as_str()))
        };
        let (Some((at, Some(name))), Some((_, Some(version)))) =
            (string("name"), string("version"))
        else {
            return Parsed::Failed;
        };
        let source = match string("source") {
            None => Source::Path,
            Some((_, None)) => return Parsed::Failed,
            Some((_, Some(s))) if CRATES_IO.contains(&s) => Source::Registry,
            Some((_, Some(s))) if s.starts_with("git+") => Source::Git,
            Some(_) => Source::OtherRegistry,
        };
        out.push(Dep {
            at: At::Line(breaks.partition_point(|&b| b < at) + 1),
            name: name.to_string(),
            version: Some(version.to_string()),
            source,
        });
    }
    Parsed::Deps("crates.io", out, Vec::new())
}

#[cfg(test)]
mod tests {
    use super::super::tests::{CARGO, Dir};
    use crate::store::Cause;

    #[test]
    fn a_crate_from_a_path_git_or_another_registry_is_never_named_as_the_crates_io_one() {
        // The workspace's own crate, a crate patched to a path, one from git and one from
        // another registry share names with crates.io's at will; only an entry from
        // crates.io's index, in either form, is named bare. An unused patch is not there.
        let dir = Dir::new("cargo", &[("Cargo.lock", CARGO)]);
        let (o, said) = dir.read();
        let at = "dev/shop/Cargo.lock";
        assert_eq!(
            said,
            [
                format!("crates.io/app (path)|part_of|checkout|{at}:6"),
                format!("crates.io/app (path)|has_version|0.1.0|{at}:6"),
                format!("crates.io/internal-crate (other registry)|part_of|checkout|{at}:17"),
                format!("crates.io/internal-crate (other registry)|has_version|1.2.0|{at}:17"),
                format!("crates.io/libc (path)|part_of|checkout|{at}:23"),
                format!("crates.io/libc (path)|has_version|0.2.191|{at}:23"),
                format!("crates.io/rand|part_of|checkout|{at}:27"),
                format!("crates.io/rand|has_version|0.8.5|{at}:27"),
                format!("crates.io/rand (git)|part_of|checkout|{at}:33"),
                format!("crates.io/rand (git)|has_version|0.9.0-dev|{at}:33"),
                format!("crates.io/serde|part_of|checkout|{at}:38"),
                format!("crates.io/serde|has_version|1.0.210|{at}:38"),
            ]
        );
        assert_eq!(o.completeness, "full");
    }

    /// The start of an invented `Cargo.lock` as cargo writes it, with the root crate `quill`.
    const CARGO_HEAD: &str = r#"# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "quill"
version = "0.3.0"
dependencies = [
 "tallow",
]
"#;

    /// What a `Cargo.lock` of `CARGO_HEAD` and the crate `tallow` 2.4.1 from crates.io says,
    /// with `tallow`'s name on `line`.
    fn tallow_read(text: &str, tag: &str, line: usize) {
        let dir = Dir::new(tag, &[("Cargo.lock", text)]);
        let (o, said) = dir.read();
        let at = "dev/shop/Cargo.lock";
        assert_eq!(
            said,
            [
                format!("crates.io/quill (path)|part_of|checkout|{at}:6"),
                format!("crates.io/quill (path)|has_version|0.3.0|{at}:6"),
                format!("crates.io/tallow|part_of|checkout|{at}:{line}"),
                format!("crates.io/tallow|has_version|2.4.1|{at}:{line}"),
            ],
            "{tag}"
        );
        assert_eq!((o.completeness, o.reason), ("full", None), "{tag}");
    }

    #[test]
    fn a_cargo_package_whose_header_carries_a_comment_is_read() {
        // Cargo reads a comment after `[[package]]`; a reader that skipped the block would say
        // the crate is not there.
        let text = format!(
            "{CARGO_HEAD}
[[package]] # kept back for the release
name = \"tallow\"
version = \"2.4.1\"
source = \"registry+https://github.com/rust-lang/crates.io-index\"
checksum = \"4444444444444444444444444444444444444444444444444444444444444444\"
"
        );
        tallow_read(&text, "cargo-comment", 13);
    }

    #[test]
    fn a_cargo_name_version_and_source_in_single_quotes_are_read_without_the_quotes() {
        // A literal string is a string: kept with its quotes it would match no advisory, and
        // its source would not be crates.io's.
        let text = format!(
            "{CARGO_HEAD}
[[package]]
name = 'tallow'
version = '2.4.1'
source = 'sparse+https://index.crates.io/'
"
        );
        tallow_read(&text, "cargo-literal", 13);
    }

    #[test]
    fn keys_in_another_order_blank_lines_and_comments_between_keys_change_nothing_in_a_cargo_lock()
    {
        let text = format!(
            "{CARGO_HEAD}
[[package]]
checksum = \"4444444444444444444444444444444444444444444444444444444444444444\"
source = \"registry+https://github.com/rust-lang/crates.io-index\"

# the version the release was tested with
version = \"2.4.1\" # pinned

name = \"tallow\"
dependencies = [
 \"quill\",
]
"
        );
        tallow_read(&text, "cargo-order", 19);
    }

    #[test]
    fn a_cargo_lock_that_is_not_toml_or_not_of_its_shape_is_a_failed_reading_never_one_with_fewer_crates()
     {
        // Each of these would otherwise be read as a lockfile naming fewer crates than it
        // does, and an advisory about the missing one would find nothing.
        let tallow = "name = \"tallow\"\nversion = \"2.4.1\"\n";
        for (tag, text) in [
            ("open-header", format!("{CARGO_HEAD}\n[[package]\n{tallow}")),
            (
                "twice",
                format!("{CARGO_HEAD}\n[[package]]\n{tallow}{tallow}"),
            ),
            ("table", format!("version = 4\n\n[package]\n{tallow}")),
            ("not-tables", "version = 4\npackage = [1]\n".to_string()),
        ] {
            cargo_failed(&format!("cargo-{tag}"), &text);
        }
        // A lockfile with no crate at all names none, and that is a reading in full.
        let dir = Dir::new("cargo-empty", &[("Cargo.lock", "version = 4\n")]);
        let (o, said) = dir.read();
        assert!(said.is_empty(), "{said:?}");
        assert_eq!((o.completeness, o.reason), ("full", None));
    }

    #[test]
    fn a_cargo_package_without_a_name_or_a_version_as_strings_is_a_failed_reading() {
        let source = "source = \"registry+https://github.com/rust-lang/crates.io-index\"\n";
        for (tag, entry) in [
            ("no-name", format!("version = \"2.4.1\"\n{source}")),
            ("no-version", format!("name = \"tallow\"\n{source}")),
            (
                "number",
                format!("name = \"tallow\"\nversion = 2\n{source}"),
            ),
            (
                "array",
                format!("name = [\"tallow\"]\nversion = \"2.4.1\"\n{source}"),
            ),
            (
                "source",
                "name = \"tallow\"\nversion = \"2.4.1\"\nsource = 1\n".to_string(),
            ),
        ] {
            cargo_failed(
                &format!("cargo-{tag}"),
                &format!("{CARGO_HEAD}\n[[package]]\n{entry}"),
            );
        }
    }

    /// A `Cargo.lock` that is not read: no crate is said of it, and the reading failed.
    fn cargo_failed(tag: &str, text: &str) {
        let dir = Dir::new(tag, &[("Cargo.lock", text)]);
        let (o, said) = dir.read();
        assert!(said.is_empty(), "{tag}: {said:?}");
        assert_eq!(
            (o.completeness, o.reason.as_deref(), o.gap.cause),
            (
                "partial",
                Some("could not be read: Cargo.lock"),
                Some(Cause::Failed)
            ),
            "{tag}"
        );
    }
}
