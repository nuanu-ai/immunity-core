//! The reader of `pdm.lock`.

use super::pypi::{pypi_files, toml_lock};
use super::{Parsed, Source};

pub(super) const READ: Option<super::Reader> = Some(|text, _| pdm(text));

/// The keys that make an entry a requirement of version control, in the order PDM's
/// `Requirement.from_req_dict` tries them (`VCS_SCHEMA`).
const VCS: [&str; 4] = ["git", "hg", "svn", "bzr"];

/// `pdm.lock` of `metadata.lock_version` 4.0 to 4.5 with any third part, the versions PDM 2.17
/// and later read: every table of the array `package`, by its name normalised, at the line of its
/// name. PDM reads an entry as `Requirement.from_req_dict` does: the first key of version control
/// present makes it one (`git` is git), else `path` (a path) or `url` (another registry), else it
/// is a named requirement. PDM records no index for a named one and installs it from the index
/// the project configures, taken here to be PyPI, checking each file against its hash in `files`.
/// So it is PyPI's when its files are all PyPI's files of its name and version (`pypi_files`):
/// file names, or addresses with the strategy `static_urls`. A file that is not TOML, no
/// `lock_version` as a string, a `package` that is not an array of tables, and an entry whose
/// name, or version where there is one, is not a string fail the reading. Another `lock_version`
/// is a kind with no reader. Left not told: a name that is not valid, version control other than
/// git, both `path` and `url`, `editable` with neither, and a named entry with no version or with
/// files that are none or not all PyPI's.
fn pdm(text: &str) -> Parsed {
    toml_lock(
        text,
        "pdm.lock",
        "lock_version",
        |v| match v.split('.').collect::<Vec<_>>()[..] {
            ["4", minor] => matches!(minor, "0" | "1" | "2" | "3" | "4" | "5"),
            ["4", minor, micro] => {
                matches!(minor, "0" | "1" | "2" | "3" | "4" | "5")
                    && !micro.is_empty()
                    && micro.bytes().all(|c| c.is_ascii_digit())
            }
            _ => false,
        },
        |package, name| {
            let version = match package.get("version").map(|v| v.get_ref().as_str()) {
                None => None,
                Some(Some(version)) => Some(version),
                Some(None) => return Err(()),
            };
            let has = |key: &str| package.contains_key(key);
            let source = match VCS.iter().find(|key| has(key)) {
                Some(&"git") => Some(Source::Git),
                Some(_) => None,
                None if has("path") && has("url") => None,
                None if has("path") => Some(Source::Path),
                None if has("url") => Some(Source::OtherRegistry),
                None if has("editable") => None,
                None => version
                    .zip(name)
                    .filter(|(v, n)| pypi_files(package.get("files").map(|f| f.get_ref()), n, v))
                    .map(|_| Source::Registry),
            };
            Ok(source.map(|source| (source, version.map(str::to_string))))
        },
    )
}

#[cfg(test)]
mod tests {
    use super::super::tests::{Dir, one_not_told, read_one};
    use crate::store::Cause;

    const HASH: &str = "abababababababababababababababababababababababababababababababab";

    /// Two files of PyPI's in the shape PDM writes them, for `name` and `version`.
    fn files(name: &str, version: &str) -> String {
        format!(
            "files = [\n    {{file = \"{name}-{version}-py3-none-any.whl\", hash = \"sha256:{HASH}\"}},\n    {{file = \"{name}-{version}.tar.gz\", hash = \"sha256:{HASH}\"}},\n]\n"
        )
    }

    /// A `pdm.lock` of `lock_version` 4.5.0 as PDM 2.17 writes it, with every source an entry can
    /// have. Names and addresses are invented.
    fn lock() -> String {
        let at = "https://files.pythonhosted.org/packages/3a/1b/0123456789abcdef0123456789abcdef0123456789abcdef0123456789ab";
        format!(
            r#"# This file is @generated by PDM.
# It is not intended for manual editing.

[metadata]
groups = ["default", "dev"]
strategy = ["inherit_metadata"]
lock_version = "4.5.0"
content_hash = "sha256:{HASH}"

[[metadata.targets]]
requires_python = ">=3.9"

[[package]]
name = "friendly-bard"
version = "1.2.0"
requires_python = ">=3.9"
summary = "An invented package"
groups = ["default"]
{bard}
[[package]]
name = "Static_Gadget"
version = "2.0.0"
summary = ""
groups = ["dev"]
marker = "sys_platform == \"darwin\""
files = [{{url = "{at}/static_gadget-2.0.0.tar.gz", hash = "sha256:{HASH}"}}]

[[package]]
name = "tool"
version = "0.3.0"
git = "https://example.invalid/tool.git"
ref = "main"
revision = "{commit}"
summary = ""
groups = ["default"]

[[package]]
name = "fetched"
version = "1.0.0"
url = "https://example.invalid/fetched-1.0.0.tar.gz"
summary = ""
groups = ["default"]
files = [{{file = "fetched-1.0.0.tar.gz", hash = "sha256:{HASH}"}}]

[[package]]
name = "vendored"
version = "1.0.0"
path = "./vendor/vendored-1.0.0.tar.gz"
summary = ""
groups = ["default"]

[[package]]
name = "sibling"
path = "./packages/sibling"
editable = true
summary = ""
groups = ["default"]
"#,
            bard = files("friendly_bard", "1.2.0"),
            commit = "c".repeat(40),
        )
    }

    #[test]
    fn a_pdm_entry_is_pypi_s_only_as_a_named_requirement_with_every_file_pypi_s() {
        // An entry from git, an address, an archive or a folder can share a name with PyPI's at
        // will: only a named one whose files, by name or by address, are of its name and version
        // carries the bare name an advisory gives. Two spellings are one name.
        let (said, reason) = read_one("pdm", "pdm.lock", &lock());
        let at = "dev/shop/pdm.lock";
        assert_eq!(
            said,
            [
                format!("PyPI/fetched (other registry)|part_of|checkout|{at}:42"),
                format!("PyPI/fetched (other registry)|has_version|1.0.0|{at}:42"),
                format!("PyPI/friendly-bard|part_of|checkout|{at}:14"),
                format!("PyPI/friendly-bard|has_version|1.2.0|{at}:14"),
                format!("PyPI/sibling (path)|part_of|checkout|{at}:57"),
                format!("PyPI/static-gadget|part_of|checkout|{at}:25"),
                format!("PyPI/static-gadget|has_version|2.0.0|{at}:25"),
                format!("PyPI/tool (git)|part_of|checkout|{at}:33"),
                format!("PyPI/tool (git)|has_version|0.3.0|{at}:33"),
                format!("PyPI/vendored (path)|part_of|checkout|{at}:50"),
                format!("PyPI/vendored (path)|has_version|1.0.0|{at}:50"),
            ]
        );
        assert_eq!(reason, None);
    }

    #[test]
    fn a_pdm_entry_whose_files_name_or_keys_do_not_tell_it_is_not_told_never_dropped() {
        // Each changes the first package only, at line 14, and that package is left not told.
        let lock = lock();
        let bard = one_not_told("pdm.lock#L14");
        let summary = "summary = \"An invented package\"\n";
        let with = |key: &str| format!("{summary}{key}\n");
        for (case, from, to) in [
            (
                "no files",
                files("friendly_bard", "1.2.0"),
                "files = []\n".to_string(),
            ),
            (
                "no files key",
                files("friendly_bard", "1.2.0"),
                String::new(),
            ),
            (
                "files of another version",
                files("friendly_bard", "1.2.0"),
                files("friendly_bard", "1.2.1"),
            ),
            ("no version", "version = \"1.2.0\"\n".into(), String::new()),
            (
                "a name not valid",
                "\"friendly-bard\"".into(),
                "\"friendly-bard-\"".into(),
            ),
            (
                "mercurial",
                summary.into(),
                with("hg = \"https://example.invalid/bard\""),
            ),
            (
                "an editable with no path",
                summary.into(),
                with("editable = true"),
            ),
            (
                "both a path and an address",
                summary.into(),
                with("path = \"./bard\"\nurl = \"https://example.invalid/bard.tar.gz\""),
            ),
        ] {
            let text = lock.replacen(&from, &to, 1);
            assert_ne!(text, lock, "{case}");
            let (said, reason) = read_one("pdm-told", "pdm.lock", &text);
            assert_eq!(reason, bard, "{case}");
            assert_eq!(said.len(), 9, "{case}");
        }
        // Git is taken before any other key, as PDM takes it.
        let text = lock.replacen(
            summary,
            &with("git = \"https://example.invalid/bard.git\""),
            1,
        );
        let (said, reason) = read_one("pdm-git", "pdm.lock", &text);
        assert!(said.contains(
            &"PyPI/friendly-bard (git)|has_version|1.2.0|dev/shop/pdm.lock:14".to_string()
        ));
        assert_eq!(reason, None);
    }

    #[test]
    fn a_pdm_lock_pdm_would_refuse_fails_and_another_lock_version_is_a_kind_with_no_reader() {
        let lock = lock();
        for (case, from, to) in [
            ("not toml", "[[package]]", "[[package]"),
            (
                "a duplicate key",
                "version = \"1.2.0\"",
                "version = \"1.2.0\"\nversion = \"1.2.0\"",
            ),
            (
                "a version not a string",
                "version = \"1.2.0\"",
                "version = 1",
            ),
            ("no name", "name = \"friendly-bard\"\n", ""),
            (
                "a name not a string",
                "name = \"friendly-bard\"",
                "name = 1",
            ),
            ("no lock_version", "lock_version = \"4.5.0\"\n", ""),
            (
                "a lock_version not a string",
                "lock_version = \"4.5.0\"",
                "lock_version = 4.5",
            ),
            (
                "a lock_version of no shape",
                "lock_version = \"4.5.0\"",
                "lock_version = \"4 5\"",
            ),
        ] {
            let text = lock.replacen(from, to, 1);
            assert_ne!(text, lock, "{case}");
            let dir = Dir::new("pdm-failed", &[("pdm.lock", &text)]);
            let (o, said) = dir.read();
            assert!(said.is_empty(), "{case}: {said:?}");
            assert_eq!(
                (o.reason.as_deref(), o.gap.cause),
                (Some("could not be read: pdm.lock"), Some(Cause::Failed)),
                "{case}"
            );
        }
        // A `package` that is not an array of tables.
        for package in [
            "package = 1",
            "package = [1]",
            "[package]\nname = \"widget\"",
        ] {
            let text = format!("{package}\n[metadata]\nlock_version = \"4.5.0\"\n");
            let (said, reason) = read_one("pdm-shape", "pdm.lock", &text);
            assert!(said.is_empty(), "{package}");
            assert_eq!(
                reason.as_deref(),
                Some("could not be read: pdm.lock"),
                "{package}"
            );
        }
        for version in ["4.0", "4.5", "4.0.0", "4.4.2", "4.5.12"] {
            let text = lock.replace("\"4.5.0\"", &format!("\"{version}\""));
            let (said, reason) = read_one("pdm-read", "pdm.lock", &text);
            assert_eq!((said.len(), reason), (11, None), "{version}");
        }
        for version in [
            "3.1", "4.6", "4.6.0", "5.0", "4", "4.5.0.1", "4.5.", "4.5.x", "4.x",
        ] {
            let text = lock.replace("\"4.5.0\"", &format!("\"{version}\""));
            let (said, reason) = read_one("pdm-version", "pdm.lock", &text);
            assert!(said.is_empty(), "{version}");
            let named = format!("not supported yet: pdm.lock version {version}");
            assert_eq!(reason, Some(named), "{version}");
        }
    }
}
