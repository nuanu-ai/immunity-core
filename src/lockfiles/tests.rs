/// What a reading of `file` holding `text` says, and its reason.
pub(super) fn read_one(tag: &str, file: &str, text: &str) -> (Vec<String>, Option<String>) {
    let dir = Dir::new(tag, &[(file, text)]);
    let (o, said) = dir.read();
    (said, o.reason)
}

