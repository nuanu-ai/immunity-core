//! The reader of `poetry.lock`.

use super::pypi::{pypi_files, toml_lock};
use super::{Parsed, Source};

pub(super) const READ: Option<super::Reader> = Some(|text, _| poetry(text));

/// `poetry.lock` of `metadata.lock-version` 2.0 or 2.1, as Poetry 1.3 and later write it: every
/// table of the array `package`, by its name normalised, at the line of its name. Poetry writes
/// `[package.source]` only for a package with a source address (`Locker._dump_package`): of
/// `type` `legacy`, another index, or `url`, it is another registry; `git` is git; `file` and
/// `directory` are a path. A package with no source was taken from PyPI when the file was
/// written, and Poetry installs it from the index the project configures, taken here to be PyPI,
/// checking each file against its hash in `files`. So it is PyPI's when its files are all PyPI's
/// files of its name and version (`pypi_files`). A file that is not TOML, no `lock-version` as a
/// string, a `package` that is not an array of tables, and a package whose name or version is not
/// a string or whose source is not a table fail the reading, as they fail Poetry. Another
/// `lock-version` is a kind with no reader. Left not told: a name that is not valid, a source of
/// another type or none, and a package with no source whose files are none or not all PyPI's.
fn poetry(text: &str) -> Parsed {
    toml_lock(
        text,
        "poetry.lock",
        "lock-version",
        |v| matches!(v, "2.0" | "2.1"),
        |package, name| {
            let Some(Some(version)) = package.get("version").map(|v| v.get_ref().as_str()) else {
                return Err(());
            };
            let source = match package.get("source").map(|s| s.get_ref()) {
                None => name
                    .filter(|name| {
                        pypi_files(package.get("files").map(|f| f.get_ref()), name, version)
                    })
                    .map(|_| Source::Registry),
                Some(toml::de::DeValue::Table(source)) => {
                    match source.get("type").and_then(|t| t.get_ref().as_str()) {
                        Some("legacy" | "url") => Some(Source::OtherRegistry),
                        Some("git") => Some(Source::Git),
                        Some("file" | "directory") => Some(Source::Path),
                        _ => None,
                    }
                }
                Some(_) => return Err(()),
            };
            Ok(source.map(|source| (source, Some(version.to_string()))))
        },
    )
}

#[cfg(test)]
mod tests {
    use super::super::tests::{Dir, read_one};
    use crate::store::Cause;

    /// Two files of PyPI's in the shape Poetry writes them, for `name` and `version`.
    fn files(name: &str, version: &str) -> String {
        format!(
            "files = [\n    {{file = \"{name}-{version}-py3-none-any.whl\", hash = \"sha256:{h}\"}},\n    {{file = \"{name}-{version}.tar.gz\", hash = \"sha256:{h}\"}},\n]\n",
            h = "ab".repeat(32)
        )
    }

    /// A `poetry.lock` of `lock-version` 2.1 as Poetry 2 writes it, with every source a package
    /// can have. Names and addresses are invented.
    fn lock() -> String {
        format!(
            r#"# This file is automatically @generated by Poetry 2.1.0 and should not be changed by hand.

[[package]]
name = "Friendly.Bard"
version = "1.2.0"
description = "An invented package"
optional = false
python-versions = ">=3.9"
groups = ["main"]
{bard}
[[package]]
name = "gadget"
version = "2.0.0"
description = ""
optional = false
python-versions = "*"
groups = ["dev"]
markers = "sys_platform == \"darwin\""
{gadget}
[package.source]
type = "legacy"
url = "https://pypi.example.invalid/simple"
reference = "private"

[[package]]
name = "tool"
version = "0.3.0"
description = ""
optional = false
python-versions = "*"
groups = ["main"]
files = []
develop = false

[package.source]
type = "git"
url = "https://example.invalid/tool.git"
reference = "main"
resolved_reference = "{commit}"

[[package]]
name = "fetched"
version = "1.0.0"
description = ""
optional = false
python-versions = "*"
groups = ["main"]
files = [{{file = "fetched-1.0.0.tar.gz", hash = "sha256:{hash}"}}]

[package.source]
type = "url"
url = "https://example.invalid/fetched-1.0.0.tar.gz"

[[package]]
name = "vendored"
version = "1.0.0"
description = ""
optional = false
python-versions = "*"
groups = ["main"]
files = [{{file = "vendored-1.0.0.tar.gz", hash = "sha256:{hash}"}}]

[package.source]
type = "file"
url = "dist/vendored-1.0.0.tar.gz"

[[package]]
name = "sibling"
version = "0.1.0"
description = ""
optional = false
python-versions = "*"
groups = ["main"]
files = []
develop = true

[package.source]
type = "directory"
url = "../sibling"

[metadata]
lock-version = "2.1"
python-versions = ">=3.9"
content-hash = "{hash}"
"#,
            bard = files("friendly_bard", "1.2.0"),
            gadget = files("gadget", "2.0.0"),
            commit = "c".repeat(40),
            hash = "ab".repeat(32),
        )
    }

    #[test]
    fn a_poetry_package_is_pypi_s_only_with_no_source_of_its_own_and_every_file_pypi_s() {
        // A package from another index, git, an address, an archive or a folder can share a
        // name with PyPI's at will: only one with no source of its own and files of its name and
        // version carries the bare name an advisory gives. Two spellings are one name.
        let (said, reason) = read_one("poetry", "poetry.lock", &lock());
        let at = "dev/shop/poetry.lock";
        assert_eq!(
            said,
            [
                format!("PyPI/fetched (other registry)|part_of|checkout|{at}:50"),
                format!("PyPI/fetched (other registry)|has_version|1.0.0|{at}:50"),
                format!("PyPI/friendly-bard|part_of|checkout|{at}:4"),
                format!("PyPI/friendly-bard|has_version|1.2.0|{at}:4"),
                format!("PyPI/gadget (other registry)|part_of|checkout|{at}:16"),
                format!("PyPI/gadget (other registry)|has_version|2.0.0|{at}:16"),
                format!("PyPI/sibling (path)|part_of|checkout|{at}:76"),
                format!("PyPI/sibling (path)|has_version|0.1.0|{at}:76"),
                format!("PyPI/tool (git)|part_of|checkout|{at}:34"),
                format!("PyPI/tool (git)|has_version|0.3.0|{at}:34"),
                format!("PyPI/vendored (path)|part_of|checkout|{at}:63"),
                format!("PyPI/vendored (path)|has_version|1.0.0|{at}:63"),
            ]
        );
        assert_eq!(reason, None);
    }

    #[test]
    fn a_poetry_package_whose_files_name_or_source_do_not_tell_it_is_not_told_never_dropped() {
        // Each changes the first package only, at line 4, and that package is left not told.
        let lock = lock();
        let bard = super::super::tests::one_not_told("poetry.lock#L4");
        for (case, from, to) in [
            (
                "no files",
                files("friendly_bard", "1.2.0"),
                "files = []\n".to_string(),
            ),
            (
                "no files key",
                files("friendly_bard", "1.2.0"),
                String::new(),
            ),
            (
                "files of another version",
                files("friendly_bard", "1.2.0"),
                files("friendly_bard", "1.2.1"),
            ),
            (
                "files of another name",
                files("friendly_bard", "1.2.0"),
                files("gadget", "1.2.0"),
            ),
            (
                "a name not valid",
                "Friendly.Bard".into(),
                "Friendly.Bard.".into(),
            ),
            (
                "a source of another type",
                "groups = [\"main\"]\n".into(),
                "groups = [\"main\"]\nsource = {type = \"hg\", url = \"x\"}\n".into(),
            ),
            (
                "a source with no type",
                "groups = [\"main\"]\n".into(),
                "groups = [\"main\"]\nsource = {url = \"https://pypi.org/simple\"}\n".into(),
            ),
        ] {
            let text = lock.replacen(&from, &to, 1);
            assert_ne!(text, lock, "{case}");
            let (said, reason) = read_one("poetry-told", "poetry.lock", &text);
            assert_eq!(reason, bard, "{case}");
            assert_eq!(said.len(), 10, "{case}");
        }
    }

    #[test]
    fn a_poetry_lock_poetry_would_refuse_fails_and_another_lock_version_is_a_kind_with_no_reader() {
        let lock = lock();
        for (case, from, to) in [
            ("not toml", "[[package]]", "[[package]"),
            (
                "a duplicate key",
                "version = \"1.2.0\"",
                "version = \"1.2.0\"\nversion = \"1.2.0\"",
            ),
            ("no version", "version = \"1.2.0\"\n", ""),
            (
                "a version not a string",
                "version = \"1.2.0\"",
                "version = 1",
            ),
            ("no name", "name = \"Friendly.Bard\"\n", ""),
            (
                "a name not a string",
                "name = \"Friendly.Bard\"",
                "name = 1",
            ),
            (
                "a source not a table",
                "groups = [\"main\"]\n",
                "groups = [\"main\"]\nsource = \"legacy\"\n",
            ),
            ("no lock-version", "lock-version = \"2.1\"\n", ""),
            (
                "a lock-version not a string",
                "lock-version = \"2.1\"",
                "lock-version = 2.1",
            ),
            (
                "a lock-version of no shape",
                "lock-version = \"2.1\"",
                "lock-version = \"2 1\"",
            ),
            ("no metadata", "[metadata]", "[other]"),
        ] {
            let text = lock.replacen(from, to, 1);
            assert_ne!(text, lock, "{case}");
            let dir = Dir::new("poetry-failed", &[("poetry.lock", &text)]);
            let (o, said) = dir.read();
            assert!(said.is_empty(), "{case}: {said:?}");
            assert_eq!(
                (o.reason.as_deref(), o.gap.cause),
                (Some("could not be read: poetry.lock"), Some(Cause::Failed)),
                "{case}"
            );
        }
        let table = "lock-version = \"2.1\"\n\n[package]\nname = \"widget\"\nversion = \"1.0\"\n";
        let (said, reason) = read_one(
            "poetry-table",
            "poetry.lock",
            &format!("[metadata]\n{table}"),
        );
        assert!(said.is_empty());
        assert_eq!(reason.as_deref(), Some("could not be read: poetry.lock"));
        // Version 2.0 is read as 2.1 is; 1.1, which keeps files apart from packages, and any
        // other are named with their number.
        let (said, reason) = read_one(
            "poetry-2.0",
            "poetry.lock",
            &lock.replace("\"2.1\"", "\"2.0\""),
        );
        assert_eq!((said.len(), reason), (12, None));
        for version in ["1.1", "2.2", "3.0", "2.1.0"] {
            let text = lock.replace(
                "lock-version = \"2.1\"",
                &format!("lock-version = \"{version}\""),
            );
            let (said, reason) = read_one("poetry-version", "poetry.lock", &text);
            assert!(said.is_empty(), "{version}");
            let named = format!("not supported yet: poetry.lock version {version}");
            assert_eq!(reason, Some(named), "{version}");
        }
    }
}
