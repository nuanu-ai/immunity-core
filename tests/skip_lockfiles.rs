//! Promises of a full check that does not read again the lockfiles of a project that did not
//! change (`src/unchanged.rs`): the store, and every answer given from it, is what a full
//! reading of the same bytes leaves, now and after any later check; and a reading is skipped
//! only when every file it opened has the same bytes, read by the same build, and the store
//! still holds what that reading found. Each test runs the real binary over an invented home
//! folder of projects with a lockfile of every kind the core reads; nothing of the Mac it runs
//! on is read and the network is never asked.

