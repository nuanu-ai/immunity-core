/// An invented advisory of OSV's shape: `left-pad` before 1.3.0.
const ADVISORY: &str = r#"{"id": "GHSA-0000-0000-0001", "modified": "2026-01-02T03:04:05Z", "published": "2026-01-02T03:04:05Z", "summary": "An invented flaw", "affected": [{"package": {"ecosystem": "npm", "name": "left-pad"}, "ranges": [{"type": "SEMVER", "events": [{"introduced": "0"}, {"fixed": "1.3.0"}]}]}]}"#;
const ADVISORY_ID: &str = "GHSA-0000-0000-0001";

/// A test's folder: the home folder of projects, the inputs, and the stores, each in a folder of
/// its own.
struct Estate {
    root: common::Scratch,
    /// The first second of the test: a time in a store from before it is not one of its runs.
    began: i64,
}

/// One store and the seconds each of its checks ran in, by the check's number.
struct Store {
    dir: PathBuf,
    checks: Vec<(i64, i64, usize)>,
}

fn now() -> i64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap()
        .as_secs() as i64
}

impl Estate {
    fn new(tag: &str) -> Estate {
        let root = common::Scratch::new(tag);
        let estate = Estate { root, began: now() };
        estate.lay();
        let src = estate.root.join("osv-src");
        std::fs::create_dir_all(&src).unwrap();
        std::fs::write(src.join(format!("{ADVISORY_ID}.json")), ADVISORY).unwrap();
        let zip = Command::new("/usr/bin/bsdtar")
            .args(["-c", "--format", "zip", "-f"])
            .arg(estate.root.join("osv-npm.zip"))
            .arg("-C")
            .arg(&src)
            .arg(format!("{ADVISORY_ID}.json"))
            .status()
            .unwrap();
        assert!(zip.success());
        std::fs::write(
            estate.root.join("brew.json"),
            r#"{"formulae": [], "casks": []}"#,
        )
        .unwrap();
        estate
    }

    fn home(&self) -> PathBuf {
        self.root.join("home")
    }

    fn dev(&self, rel: &str) -> PathBuf {
        self.home().join("dev").join(rel)
    }

    /// Lays every project of `matrix` anew, each a checkout as git leaves it.
    fn lay(&self) {
        common::remove(&self.home().join("dev"));
        for (rel, text) in matrix() {
            self.put(rel, &text);
            let project = rel.split('/').next().unwrap();
            self.put(&format!("{project}/.git/HEAD"), "ref: refs/heads/main\n");
            self.put(
                &format!("{project}/.git/refs/heads/main"),
                "0123456789abcdef0123456789abcdef01234567\n",
            );
        }
    }

    fn put(&self, rel: &str, text: &str) {
        let path = self.dev(rel);
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, text).unwrap();
    }

    fn store(&self, name: &str) -> Store {
        Store {
            dir: self.root.join(name),
            checks: Vec::new(),
        }
    }

    /// `immunity run` on `store` as its check number `n`, every outside source but the projects
    /// and the npm data pointed at nothing. It begins in a second of its own, so that each time
    /// a store holds tells which check wrote it.
    fn check(&self, store: &mut Store, n: usize) {
        let no = self.root.join("absent");
        common::next_second();
        let began = now();
        let mut cmd = Command::new(env!("CARGO_BIN_EXE_immunity"));
        cmd.env_clear()
            .env("HOME", self.home())
            .env("PATH", "/usr/bin:/bin")
            .current_dir(self.home())
            .args(["run", "--machine-name", "mac", "--store"])
            .arg(store.db())
            .arg("--brew-input")
            .arg(self.root.join("brew.json"))
            .arg("--osv-npm-input")
            .arg(self.root.join("osv-npm.zip"));
        for flag in [
            "--servers-input",
            "--tailscale",
            "--threats-input",
            "--osv-crates-input",
            "--osv-pypi-input",
            "--system-root",
            "--sessions-root",
        ] {
            cmd.arg(flag).arg(&no);
        }
        let out = cmd.output().unwrap();
        assert!(
            out.status.success(),
            "{}",
            String::from_utf8_lossy(&out.stderr)
        );
        store.checks.push((began, now(), n));
    }

    /// The answer of a command of the contract on `store`, as JSON, made comparable.
    fn answer(&self, store: &Store, args: &[&str]) -> String {
        let text = self.json(store, args);
        let text = text.replace(&store.dir.display().to_string(), "<store>");
        store.timeless(&text, self.began)
    }

    /// The answer of a command of the contract on `store`, as JSON.
    fn json(&self, store: &Store, args: &[&str]) -> String {
        let out = Command::new(env!("CARGO_BIN_EXE_immunity"))
            .env_clear()
            .env("HOME", self.home())
            .env("PATH", "/usr/bin:/bin")
            .current_dir(self.home())
            .args(args)
            .arg("--json")
            .arg("--store")
            .arg(store.db())
            .output()
            .unwrap();
        assert!(
            out.status.success(),
            "{args:?}: {}",
            String::from_utf8_lossy(&out.stderr)
        );
        String::from_utf8(out.stdout).unwrap()
    }
}

impl Store {
    fn db(&self) -> PathBuf {
        self.dir.join("store.db")
    }

    /// A copy of this store, its folder whole, under `name`, with every commit in its file.
    fn copy(&self, estate: &Estate, name: &str) -> Store {
        let _ = common::store_bytes(&self.db());
        let dir = estate.root.join(name);
        common::remove(&dir);
        let cp = Command::new("/bin/cp")
            .arg("-R")
            .arg(&self.dir)
            .arg(&dir)
            .status()
            .unwrap();
        assert!(cp.success());
        Store {
            dir,
            checks: self.checks.clone(),
        }
    }

    /// Forgets every record of the files a reading opened, so that its next check reads every
    /// project in full.
    fn forget(&self) {
        let conn = common::open_store(&self.db());
        conn.execute("DELETE FROM coverage_file", []).unwrap();
    }

    /// `text` with each time of one of this store's checks written as the check's number, a run's
    /// id as `run` and that number, and any other time since the test began as `later`.
    fn timeless(&self, text: &str, began: i64) -> String {
        let of = |secs: i64| {
            (self.checks.iter())
                .find(|(from, to, _)| (*from..=*to).contains(&secs))
                .map(|(.., n)| format!("t{n}"))
        };
        let ids = regex::Regex::new(r"\b(\d{10})-\d{9}\b").unwrap();
        let text = ids.replace_all(text, |c: &regex::Captures| {
            let secs = c[1].parse().unwrap();
            format!("run-{}", of(secs).unwrap_or_else(|| c[0].to_string()))
        });
        let times = regex::Regex::new(r"\b\d{10}\b").unwrap();
        times
            .replace_all(&text, |c: &regex::Captures| {
                let secs: i64 = c[0].parse().unwrap();
                match of(secs) {
                    Some(t) => t,
                    None if secs >= began => "later".to_string(),
                    None => c[0].to_string(),
                }
            })
            .into_owned()
    }

    /// Every row of every table but the record of the files readings opened, each value as text,
    /// times and run ids written by `timeless`.
    fn dump(&self, began: i64) -> Vec<String> {
        let conn = Connection::open(self.db()).unwrap();
        let tables: Vec<String> = conn
            .prepare("SELECT name FROM sqlite_master WHERE type = 'table' ORDER BY name")
            .unwrap()
            .query_map([], |r| r.get(0))
            .unwrap()
            .collect::<Result<_, _>>()
            .unwrap();
        let mut out = Vec::new();
        for table in tables.iter().filter(|t| *t != "coverage_file") {
            let mut stmt = conn.prepare(&format!("SELECT * FROM \"{table}\"")).unwrap();
            let n = stmt.column_count();
            let mut rows: Vec<String> = stmt
                .query_map([], |r| {
                    let cells: Vec<String> = (0..n)
                        .map(|i| match r.get_ref(i).unwrap() {
                            ValueRef::Null => "NULL".to_string(),
                            ValueRef::Integer(v) => v.to_string(),
                            ValueRef::Real(v) => v.to_string(),
                            ValueRef::Text(t) => String::from_utf8_lossy(t).into_owned(),
                            ValueRef::Blob(b) => format!("{b:?}"),
                        })
                        .collect();
                    Ok(format!("{table}|{}", cells.join("|")))
                })
                .unwrap()
                .collect::<Result<_, _>>()
                .unwrap();
            rows.sort();
            out.extend(rows.into_iter().map(|row| self.timeless(&row, began)));
        }
        out
    }
}

/// Every answer the promise names, from `store`.
fn answers(estate: &Estate, store: &Store) -> Vec<String> {
    let mut asked: Vec<Vec<&str>> = vec![
        vec!["status"],
        vec!["findings", "--all"],
        vec!["vulnerabilities"],
        vec!["vulnerability", ADVISORY_ID],
    ];
    let projects: Vec<String> = matrix()
        .iter()
        .map(|(rel, _)| {
            format!(
                "checkout:machine:mac/dev/{}",
                rel.split('/').next().unwrap()
            )
        })
        .collect();
    asked.extend(projects.iter().map(|p| vec!["project", p.as_str()]));
    (asked.iter())
        .map(|args| format!("{args:?} {}", estate.answer(store, args)))
        .collect()
}

/// The store that skips and the store read in full every time are the same, and so is every
/// answer, at `when`.
fn same(estate: &Estate, skipping: &Store, full: &Store, when: &str) {
    let (a, b) = (skipping.dump(estate.began), full.dump(estate.began));
    let differ: Vec<(&String, &String)> = a.iter().zip(&b).filter(|(x, y)| x != y).collect();
    assert!(
        a.len() == b.len() && differ.is_empty(),
        "{when}: {} rows and {}, first differences {:#?}",
        a.len(),
        b.len(),
        &differ[..differ.len().min(5)]
    );
    for (x, y) in answers(estate, skipping).iter().zip(answers(estate, full)) {
        assert_eq!(*x, y, "{when}");
    }
}

#[test]
fn a_check_that_skips_unchanged_lockfiles_leaves_the_store_and_every_answer_as_a_full_reading_does()
{
    // No false calm and nothing said that was not done. One store skips what did not change;
    // the other forgets every record before each check, so every project is read in full.
    // After the second check, and after a third that follows each change a project can see,
    // every table but the record and every answer of the promise are the same.
    let estate = Estate::new("skip-same");
    let mut first = estate.store("first");
    estate.check(&mut first, 1);
    let (mut skipping, mut full) = (first.copy(&estate, "a2"), first.copy(&estate, "b2"));
    estate.check(&mut skipping, 2);
    full.forget();
    estate.check(&mut full, 2);
    same(&estate, &skipping, &full, "a second check, nothing changed");
    let npm = estate.dev("npm/package-lock.json");
    type Change = fn(&Estate);
    let changes: [(&str, Change); 6] = [
        ("nothing changed", |_| {}),
        ("one byte, the size kept", |e| {
            e.put("npm/package-lock.json", &npm_lock("1.3.1"));
        }),
        ("a dependency moved to a vulnerable version", |e| {
            e.put("npm/package-lock.json", &npm_lock("1.2.0"));
        }),
        ("a lockfile removed", |e| {
            std::fs::remove_file(e.dev("pylock/pylock.dev.toml")).unwrap();
        }),
        ("a nested lockfile added", |e| {
            e.put("nested/tools/b/package-lock.json", &npm_lock("1.2.0"));
        }),
        ("the project removed", |e| common::remove(&e.dev("cargo"))),
    ];
    assert_eq!(std::fs::read_to_string(&npm).unwrap(), npm_lock("1.3.0"));
    for (i, (what, change)) in changes.iter().enumerate() {
        estate.lay();
        let mut a = skipping.copy(&estate, &format!("a3-{i}"));
        let mut b = full.copy(&estate, &format!("b3-{i}"));
        change(&estate);
        estate.check(&mut a, 3);
        b.forget();
        estate.check(&mut b, 3);
        same(&estate, &a, &b, what);
    }
    // The project removed and put back with the same bytes: the check that saw it gone let go of
    // its record, so the next reads it in full and finds it as a first reading would.
    let (mut a, mut b) = (skipping.copy(&estate, "a4"), full.copy(&estate, "b4"));
    common::remove(&estate.dev("cargo"));
    estate.check(&mut a, 3);
    b.forget();
    estate.check(&mut b, 3);
    estate.lay();
    estate.check(&mut a, 4);
    b.forget();
    estate.check(&mut b, 4);
    same(&estate, &a, &b, "the project removed and put back");
}

/// The scope of a project's readings.
fn scope(project: &str) -> String {
    format!("checkout:machine:mac/dev/{project}")
}

/// Sets every live version a project's lockfiles reading holds to one its files never declared,
/// retracting nothing, as a reading by another build might have left it: a check that reads the
/// project finds the versions in its files again, and one that skips it leaves this one.
fn tamper(store: &Store, project: &str) {
    let conn = common::open_store(&store.db());
    let n = conn
        .execute(
            "UPDATE assertion SET object = '0.0.1' WHERE layer = 'live' AND reader = 'lockfiles'
             AND predicate = 'has_version' AND scope = ?1",
            [scope(project)],
        )
        .unwrap();
    assert!(n > 0, "{project}");
}

/// The live versions a project's lockfiles reading holds, in order.
fn versions(store: &Store, project: &str) -> Vec<String> {
    let conn = Connection::open(store.db()).unwrap();
    conn.prepare(
        "SELECT object FROM assertion WHERE layer = 'live' AND reader = 'lockfiles'
         AND predicate = 'has_version' AND scope = ?1 ORDER BY object",
    )
    .unwrap()
    .query_map([scope(project)], |r| r.get(0))
    .unwrap()
    .collect::<Result<_, _>>()
    .unwrap()
}

/// The latest coverage of a project's lockfiles reading: completeness, reason and run.
fn latest(store: &Store, project: &str) -> (String, Option<String>, String) {
    let conn = Connection::open(store.db()).unwrap();
    conn.query_row(
        "SELECT completeness, reason, run_id FROM coverage
         WHERE reader = 'lockfiles' AND scope = ?1 ORDER BY id DESC LIMIT 1",
        [scope(project)],
        |r| Ok((r.get(0)?, r.get(1)?, r.get(2)?)),
    )
    .unwrap()
}

/// The id of the run a store's check `n` was.
fn run_of(store: &Store, n: usize) -> String {
    let conn = Connection::open(store.db()).unwrap();
    let ids: Vec<String> = conn
        .prepare("SELECT run_id FROM journal WHERE entry = 'run_started' ORDER BY seq")
        .unwrap()
        .query_map([], |r| r.get(0))
        .unwrap()
        .collect::<Result<_, _>>()
        .unwrap();
    ids[n - 1].clone()
}

/// Runs `sql` on a store as a writer that is not the core would.
fn change(store: &Store, sql: &str) {
    common::open_store(&store.db()).execute_batch(sql).unwrap();
}

#[test]
fn a_project_whose_lockfiles_are_unchanged_is_not_read_again_and_is_said_read_by_this_check() {
    // The skip is real for every reader: a version set by hand stays. And what a person is told
    // is true: the latest reading of each project is full, of the second check, and its answer
    // says it was read in full by that check, which compared every byte.
    let estate = Estate::new("skip-real");
    let mut store = estate.store("s");
    estate.check(&mut store, 1);
    let projects: Vec<&str> = (matrix()
        .iter()
        .map(|(rel, _)| rel.split('/').next().unwrap()))
    .collect();
    for project in &projects {
        tamper(&store, project);
    }
    estate.check(&mut store, 2);
    let second = run_of(&store, 2);
    for project in &projects {
        assert!(
            versions(&store, project).iter().all(|v| v == "0.0.1"),
            "{project}"
        );
        assert_eq!(
            latest(&store, project),
            ("full".into(), None, second.clone())
        );
    }
    let answer: serde_json::Value =
        serde_json::from_str(&estate.json(&store, &["project", &scope("npm")])).unwrap();
    let reading = (answer["coverage"].as_array().unwrap().iter())
        .find(|c| c["reader"] == "lockfiles")
        .unwrap();
    let at: i64 = second.split('-').next().unwrap().parse().unwrap();
    assert_eq!(reading["completeness"], "full");
    assert_eq!(reading["observed_at"], at);
    assert_eq!(reading["last_full_at"], at);
    assert_eq!(reading["run_id"], second.as_str());
    // A check after a skip skips too, and the store keeps the files of each project's latest
    // reading only, so the record does not grow with the checks.
    estate.check(&mut store, 3);
    assert!(
        projects
            .iter()
            .all(|p| versions(&store, p).iter().all(|v| v == "0.0.1"))
    );
    let conn = Connection::open(store.db()).unwrap();
    let kept: i64 = conn
        .query_row(
            "SELECT COUNT(*) FROM coverage_file f JOIN coverage c ON c.id = f.coverage
             WHERE c.run_id = ?1",
            [run_of(&store, 3)],
            |r| r.get(0),
        )
        .unwrap();
    let all: i64 = conn
        .query_row("SELECT COUNT(*) FROM coverage_file", [], |r| r.get(0))
        .unwrap();
    assert_eq!((kept, all), (matrix().len() as i64, matrix().len() as i64));
}

#[test]
fn a_project_is_read_again_when_a_file_its_reading_opens_changes_appears_or_goes_or_a_folder_cannot_be_listed()
 {
    // No false calm: a vulnerability not found is a lockfile changed and skipped. Each change is
    // made after a version was set by hand, so a reading done again is told by the versions in
    // the files coming back. A reading done again says what a full reading says: a lockfile
    // found and not opened, or a folder that cannot be listed, leaves it partial, so what was
    // set by hand is held beside what the files say.
    use std::os::unix::fs::PermissionsExt;
    let estate = Estate::new("skip-changed");
    let mut first = estate.store("first");
    estate.check(&mut first, 1);
    type Change = fn(&Estate);
    let cases: [(&str, &str, Change, &[&str]); 8] = [
        (
            "one byte, the size kept",
            "npm",
            |e| e.put("npm/package-lock.json", &npm_lock("1.3.1")),
            &["1.3.1"],
        ),
        (
            "a nested lockfile changed",
            "nested",
            |e| {
                e.put(
                    "nested/tools/a/Cargo.lock",
                    &CARGO.replace("0.8.5", "0.8.6"),
                );
            },
            &["0.8.6", "1.3.0"],
        ),
        (
            "a lockfile appeared",
            "nested",
            |e| {
                e.put("nested/tools/b/Cargo.lock", CARGO);
            },
            &["0.8.5", "1.3.0"],
        ),
        (
            "a lockfile went",
            "pylock",
            |e| {
                std::fs::remove_file(e.dev("pylock/pylock.dev.toml")).unwrap();
            },
            &["1.2.0"],
        ),
        (
            "a named lock appeared beside",
            "pylock",
            |e| e.put("pylock/pylock.new.toml", &pylock()),
            &["1.2.0"],
        ),
        (
            "a folder that cannot be listed",
            "npm",
            |e| {
                let folder = e.dev("npm/sub");
                std::fs::create_dir_all(&folder).unwrap();
                std::fs::set_permissions(&folder, std::fs::Permissions::from_mode(0o000)).unwrap();
            },
            &["0.0.1", "1.3.0"],
        ),
        (
            "a lockfile appeared below the folders opened",
            "npm",
            |e| e.put("npm/a/b/c/d/e/package-lock.json", &npm_lock("1.3.0")),
            &["0.0.1", "1.3.0"],
        ),
        (
            "a lockfile with no reader appeared",
            "npm",
            |e| e.put("npm/Gemfile.lock", "GEM\n"),
            &["0.0.1", "1.3.0"],
        ),
    ];
    for (i, (what, project, change, now)) in cases.iter().enumerate() {
        estate.lay();
        let mut store = first.copy(&estate, &format!("s{i}"));
        tamper(&store, project);
        change(&estate);
        estate.check(&mut store, 2);
        assert_eq!(versions(&store, project), *now, "{what}");
        let partial = now.contains(&"0.0.1");
        let completeness = latest(&store, project).0;
        assert_eq!(completeness == "partial", partial, "{what}: {completeness}");
    }
}

#[test]
fn a_project_read_by_another_build_is_read_again() {
    // A reader that changed may read the same bytes into other facts. The record names the
    // build that read; another build's record is not this build's.
    let estate = Estate::new("skip-build");
    let mut store = estate.store("s");
    estate.check(&mut store, 1);
    change(
        &store,
        "UPDATE coverage_file SET build = 'another build' WHERE path LIKE 'dev/npm/%'",
    );
    tamper(&store, "npm");
    tamper(&store, "cargo");
    estate.check(&mut store, 2);
    assert_eq!(versions(&store, "npm"), ["1.3.0"]);
    assert_eq!(versions(&store, "cargo"), ["0.0.1"]);
}

#[test]
fn a_project_whose_latest_reading_was_partial_or_failed_is_read_again() {
    // Only a full reading is recorded, and only the latest reading's record counts: a reading
    // that did not read everything, or a lockfile that could not be read since, leaves nothing
    // to skip by. A file a lockfile includes is not read, so such a reading is partial and is
    // read again whatever the included file holds.
    use std::os::unix::fs::PermissionsExt;
    let estate = Estate::new("skip-partial");
    estate.put(
        "inc/requirements.txt",
        &format!("widget==1.2.0 --hash=sha256:{H}\n-r base.txt\n"),
    );
    estate.put("inc/base.txt", "gadget==2.0.0\n");
    estate.put("inc/.git/HEAD", "ref: refs/heads/main\n");
    let mut store = estate.store("s");
    estate.check(&mut store, 1);
    assert_eq!(latest(&store, "inc").0, "partial");
    estate.put("inc/base.txt", "gadget==2.0.1\n");
    tamper(&store, "inc");
    estate.check(&mut store, 2);
    assert_eq!(versions(&store, "inc"), ["0.0.1", "1.2.0"]);
    // A lockfile that cannot be read now cannot be compared: the reading says so, and the next
    // one, with the file readable and its bytes as before, reads it again.
    let lock = estate.dev("npm/package-lock.json");
    std::fs::set_permissions(&lock, std::fs::Permissions::from_mode(0o000)).unwrap();
    estate.check(&mut store, 3);
    std::fs::set_permissions(&lock, std::fs::Permissions::from_mode(0o644)).unwrap();
    let (completeness, reason, _) = latest(&store, "npm");
    assert_ne!(completeness, "full");
    assert_eq!(
        reason.as_deref(),
        Some("could not be read: package-lock.json")
    );
    tamper(&store, "npm");
    estate.check(&mut store, 4);
    assert_eq!(versions(&store, "npm"), ["1.3.0"]);
}

#[test]
fn a_project_whose_facts_were_retracted_since_is_read_again() {
    // The record goes with the facts of its reading: a project that left takes them along, and
    // when it comes back with the same bytes it is read as it is found.
    let estate = Estate::new("skip-retracted");
    let mut store = estate.store("s");
    estate.check(&mut store, 1);
    estate.check(&mut store, 2);
    common::remove(&estate.dev("uv"));
    estate.check(&mut store, 3);
    assert!(versions(&store, "uv").is_empty());
    estate.lay();
    estate.check(&mut store, 4);
    assert_eq!(versions(&store, "uv"), ["1.2.0"]);
}
